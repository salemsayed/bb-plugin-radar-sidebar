import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { launch } from "./browser.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "theme");
const server = process.env.BB_SERVER_URL ?? "http://127.0.0.1:38886";

function layerBlock(css, name) {
  const start = css.indexOf(`@layer ${name}{`);
  if (start < 0) throw new Error(`bb's stylesheet has no @layer ${name}`);
  let depth = 0;
  for (let at = start; at < css.length; at++) {
    if (css[at] === "{") depth++;
    else if (css[at] === "}" && --depth === 0) return css.slice(start, at + 1);
  }
  throw new Error(`@layer ${name} never closes`);
}

async function tokens(browser, colorScheme) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme });
  const page = await context.newPage();
  await page.goto(server, { waitUntil: "networkidle", timeout: 60_000 });
  const result = await page.evaluate(() => {
    const names = new Set();
    const walk = rules => { for (const rule of rules) { if (rule.style) for (const name of rule.style) if (name.startsWith("--")) names.add(name); if (rule.cssRules) walk(rule.cssRules); } };
    for (const sheet of document.styleSheets) { try { walk(sheet.cssRules); } catch { continue; } }
    const root = getComputedStyle(document.documentElement);
    const vars = {};
    for (const name of [...names].sort()) { const value = root.getPropertyValue(name).trim(); if (value && !name.startsWith("--tw-")) vars[name] = value; }
    const sheet = [...document.querySelectorAll('link[rel="stylesheet"]')].map(link => link.href).find(href => /\/assets\/index-/.test(href));
    return { vars, sheet };
  });
  await context.close();
  return result;
}

const browser = await launch();
const light = await tokens(browser, "light");
const dark = await tokens(browser, "dark");
await browser.close();
if (!light.sheet) throw new Error(`No bb stylesheet found at ${server}`);
const css = await (await fetch(light.sheet)).text();
const faces = [...css.matchAll(/@font-face\{[^}]*\}/g)].map(match => match[0]).filter(face => /Inter Variable/.test(face) && /font-style:normal/.test(face) && /latin/.test(face));
await mkdir(out, { recursive: true });
const localFaces = [];
for (const face of faces) {
  const url = /url\(([^)]+)\)/.exec(face)?.[1];
  if (!url) continue;
  const name = url.split("/").pop().replace(/-[A-Za-z0-9_]{8}(?=\.woff2$)/, "");
  await writeFile(join(out, name), Buffer.from(await (await fetch(new URL(url, server))).arrayBuffer()));
  localFaces.push(face.replace(url, `./${name}`));
}
const block = (selector, vars, scheme) => `${selector}{color-scheme:${scheme};${Object.entries(vars).map(([name, value]) => `${name}:${value}`).join(";")}}`;
const changed = Object.fromEntries(Object.entries(dark.vars).filter(([name, value]) => light.vars[name] !== value));
const file = [
  `/* Generated by capture-theme.mjs from ${new URL(light.sheet).pathname} on ${new Date().toISOString().slice(0, 10)}. Do not edit: run "npm run theme" against a running bb. */`,
  localFaces.join("\n"),
  layerBlock(css, "base"),
  block(":root", light.vars, "light"),
  block(":root.dark", changed, "dark"),
].join("\n");
await writeFile(join(out, "bb.css"), `${file}\n`);
console.log(`theme/bb.css: ${Object.keys(light.vars).length} variables, ${Object.keys(changed).length} dark overrides, ${localFaces.length} font files`);
